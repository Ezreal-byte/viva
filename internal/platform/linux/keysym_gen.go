//go:build ignore

// keysym_gen writes keysym_unicode.go from X.Org's keysymdef.h, whose comments
// give the Unicode character of every legacy keysym (Cyrillic, Greek, Latin-2,
// Hebrew, Thai, ...):
//
//	go run keysym_gen.go /path/to/X11/keysymdef.h > keysym_unicode.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
)

var line = regexp.MustCompile(`^#define\s+XK_\S+\s+0x([0-9a-fA-F]+)\s+/\*\s*\(?<?U\+([0-9A-Fa-f]{4,6})`)

func main() {
	file, err := os.Open(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer file.Close()
	table := map[uint32]uint32{}
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		match := line.FindStringSubmatch(scanner.Text())
		if match == nil {
			continue
		}
		keysym, _ := strconv.ParseUint(match[1], 16, 32)
		character, _ := strconv.ParseUint(match[2], 16, 32)
		// The legacy blocks only: Latin-1 and the 0x01000000 Unicode keysyms
		// need no table, and function and keypad keysyms are not characters.
		if keysym < 0x100 || keysym > 0x20ff || character == 0 || character > 0xffff {
			continue
		}
		table[uint32(keysym)] = uint32(character)
	}
	keys := make([]uint32, 0, len(table))
	for keysym := range table {
		keys = append(keys, keysym)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	fmt.Println("// Code generated by keysym_gen.go from X.Org keysymdef.h; DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package linux")
	fmt.Println()
	fmt.Println("// legacyKeysymRunes maps the legacy (non-Latin-1, non-0x01000000) keysyms to")
	fmt.Println("// their characters, sorted by keysym.")
	fmt.Println("var legacyKeysymRunes = [...]struct{ keysym, character uint16 }{")
	for _, keysym := range keys {
		fmt.Printf("\t{0x%04x, 0x%04x},\n", keysym, table[keysym])
	}
	fmt.Println("}")
}
