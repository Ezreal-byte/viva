package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

type shaderEntry struct {
	Name    string `json:"name"`
	Profile string `json:"profile"`
	SHA256  string `json:"sha256"`
	Bytes   int    `json:"bytes"`
}

type shaderManifest struct {
	SourceSHA256 string        `json:"source_sha256"`
	Compiler     string        `json:"compiler"`
	Flags        uint32        `json:"flags"`
	Entries      []shaderEntry `json:"entries"`
}

var entries = [...]shaderEntry{
	{Name: "rectangleVertex", Profile: "vs_5_0"},
	{Name: "rectangleFragment", Profile: "ps_5_0"},
	{Name: "textVertex", Profile: "vs_5_0"},
	{Name: "textFragment", Profile: "ps_5_0"},
}

const compilerFlags = uint32(1<<11 | 1<<15)

func digest(data []byte) string {
	hash := sha256.Sum256(data)
	return hex.EncodeToString(hash[:])
}

func generate(source []byte, output string, compile func([]byte, string, string) ([]byte, error)) error {
	if len(source) == 0 {
		return fmt.Errorf("empty shader source")
	}
	manifest := shaderManifest{SourceSHA256: digest(source), Compiler: "d3dcompiler_47.dll", Flags: compilerFlags}
	var bytecodes [len(entries)][]byte
	for index, entry := range entries {
		code, err := compile(source, entry.Name, entry.Profile)
		if err != nil {
			return fmt.Errorf("%s: %w", entry.Name, err)
		}
		if len(code) < 32 || !bytes.Equal(code[:4], []byte("DXBC")) {
			return fmt.Errorf("%s: compiler did not return DXBC", entry.Name)
		}
		entry.Bytes, entry.SHA256 = len(code), digest(code)
		manifest.Entries = append(manifest.Entries, entry)
		bytecodes[index] = code
	}
	encoded, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(output, 0755); err != nil {
		return err
	}
	for index, entry := range entries {
		if err := os.WriteFile(filepath.Join(output, entry.Name+".dxbc"), bytecodes[index], 0644); err != nil {
			return err
		}
	}
	return os.WriteFile(filepath.Join(output, "manifest.json"), append(encoded, '\n'), 0644)
}

