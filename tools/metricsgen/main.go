// Command metricsgen reads the advance widths of the reference text font from
// TrueType files and writes internal/textmetrics/table.go.
//
//	go run ./tools/metricsgen -out internal/textmetrics/table.go -scale 0.96 Inter-Regular.ttf Inter-Medium.ttf Inter-SemiBold.ttf Inter-Bold.ttf
//
// Inter sets about 4 percent wider than the macOS system font (the face Viva's
// components were proportioned for), so the advances are multiplied by -scale and
// rounded to font units.
//
// The four files are the regular, medium, semibold and bold weights, in that order.
// Only the advance of each code point in a few ranges is kept; the rules for the
// rest (full-width, emoji, combining marks, unknown scripts) are in the package.
package main

import (
	"bytes"
	"encoding/binary"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
)

// missing marks a code point the font has no glyph for.
const missing = 0xFFFF

// ranges are the code points the table holds an advance for, in ascending order.
var ranges = [][2]rune{
	{0x0020, 0x024F}, // Basic Latin, Latin-1 Supplement, Latin Extended-A and B
	{0x0370, 0x052F}, // Greek, Cyrillic, Cyrillic Supplement
	{0x1E00, 0x1EFF}, // Latin Extended Additional
	{0x2000, 0x206F}, // General Punctuation
	{0x20A0, 0x20BF}, // Currency Symbols
	{0x2190, 0x22FF}, // Arrows, Mathematical Operators
}

func main() {
	out := flag.String("out", "table.go", "output Go file")
	scale := flag.Float64("scale", 1, "factor applied to every advance")
	flag.Parse()
	if flag.NArg() != 4 {
		fmt.Fprintln(os.Stderr, "usage: metricsgen -out table.go regular.ttf medium.ttf semibold.ttf bold.ttf")
		os.Exit(2)
	}
	var tables [4][]uint16
	var upem uint16
	for i, path := range flag.Args() {
		data, err := os.ReadFile(path)
		if err != nil {
			fail(err)
		}
		advances, unit, err := read(data)
		if err != nil {
			fail(fmt.Errorf("%s: %w", path, err))
		}
		if upem != 0 && upem != unit {
			fail(fmt.Errorf("%s: units per em %d differ from %d", path, unit, upem))
		}
		upem = unit
		for j, v := range advances {
			if v != missing {
				advances[j] = uint16(math.Round(float64(v) * *scale))
			}
		}
		tables[i] = advances
	}
	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by tools/metricsgen from the Inter font (SIL OFL 1.1), advances scaled by %g; DO NOT EDIT.\n\n", *scale)
	src.WriteString("package textmetrics\n\n")
	fmt.Fprintf(&src, "// unitsPerEm is the unit of every advance in the tables.\nconst unitsPerEm = %d\n\n", upem)
	src.WriteString("// spans are the code point ranges the tables hold, in order; a span's advances start\n// at first within each weight's table.\nvar spans = [...]span{\n")
	first := 0
	for _, r := range ranges {
		fmt.Fprintf(&src, "\t{from: %#x, to: %#x, first: %d},\n", r[0], r[1], first)
		first += int(r[1]-r[0]) + 1
	}
	src.WriteString("}\n\n")
	fmt.Fprintf(&src, "// advances holds, per weight (regular, medium, semibold, bold), the advance of every\n// code point of spans in font units; 0xFFFF is a code point the font lacks.\nvar advances = [4][%d]uint16{\n", first)
	for _, table := range tables {
		src.WriteString("\t{")
		for i, v := range table {
			if i%16 == 0 {
				src.WriteString("\n\t\t")
			} else {
				src.WriteString(" ")
			}
			fmt.Fprintf(&src, "%d,", v)
		}
		src.WriteString("\n\t},\n")
	}
	src.WriteString("}\n")
	formatted, err := format.Source(src.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "metricsgen:", err)
	os.Exit(1)
}

// read returns the advance of every code point of ranges, concatenated, and the
// font's units per em.
func read(data []byte) ([]uint16, uint16, error) {
	tables, err := directory(data)
	if err != nil {
		return nil, 0, err
	}
	head, hhea, hmtx, cmap := tables["head"], tables["hhea"], tables["hmtx"], tables["cmap"]
	if head == nil || hhea == nil || hmtx == nil || cmap == nil {
		return nil, 0, fmt.Errorf("missing head, hhea, hmtx or cmap")
	}
	upem := binary.BigEndian.Uint16(head[18:])
	metrics := int(binary.BigEndian.Uint16(hhea[34:]))
	advance := func(glyph int) uint16 {
		if glyph >= metrics {
			glyph = metrics - 1
		}
		return binary.BigEndian.Uint16(hmtx[glyph*4:])
	}
	lookup, err := cmapLookup(cmap)
	if err != nil {
		return nil, 0, err
	}
	var out []uint16
	for _, r := range ranges {
		for c := r[0]; c <= r[1]; c++ {
			if glyph := lookup(c); glyph != 0 {
				out = append(out, advance(glyph))
			} else {
				out = append(out, missing)
			}
		}
	}
	return out, upem, nil
}

func directory(data []byte) (map[string][]byte, error) {
	if len(data) < 12 {
		return nil, fmt.Errorf("short font")
	}
	count := int(binary.BigEndian.Uint16(data[4:]))
	tables := map[string][]byte{}
	for i := 0; i < count; i++ {
		entry := data[12+i*16:]
		offset, length := int(binary.BigEndian.Uint32(entry[8:])), int(binary.BigEndian.Uint32(entry[12:]))
		if offset+length > len(data) {
			return nil, fmt.Errorf("table %q outside the file", entry[:4])
		}
		tables[string(entry[:4])] = data[offset : offset+length]
	}
	return tables, nil
}

// cmapLookup maps a code point to a glyph through the best Unicode subtable: format
// 12 when there is one, otherwise format 4.
func cmapLookup(cmap []byte) (func(rune) int, error) {
	count := int(binary.BigEndian.Uint16(cmap[2:]))
	var format4, format12 []byte
	for i := 0; i < count; i++ {
		record := cmap[4+i*8:]
		platform, encoding := binary.BigEndian.Uint16(record), binary.BigEndian.Uint16(record[2:])
		sub := cmap[binary.BigEndian.Uint32(record[4:]):]
		if platform == 3 && encoding == 10 || platform == 0 && binary.BigEndian.Uint16(sub) == 12 {
			format12 = sub
		}
		if platform == 3 && encoding == 1 || platform == 0 && binary.BigEndian.Uint16(sub) == 4 {
			format4 = sub
		}
	}
	switch {
	case format12 != nil:
		groups := int(binary.BigEndian.Uint32(format12[12:]))
		return func(c rune) int {
			for i := 0; i < groups; i++ {
				g := format12[16+i*12:]
				start, end, glyph := binary.BigEndian.Uint32(g), binary.BigEndian.Uint32(g[4:]), binary.BigEndian.Uint32(g[8:])
				if uint32(c) >= start && uint32(c) <= end {
					return int(glyph + uint32(c) - start)
				}
			}
			return 0
		}, nil
	case format4 != nil:
		segments := int(binary.BigEndian.Uint16(format4[6:])) / 2
		ends := format4[14:]
		starts := format4[16+segments*2:]
		deltas := format4[16+segments*4:]
		offsets := format4[16+segments*6:]
		return func(c rune) int {
			for i := 0; i < segments; i++ {
				end := rune(binary.BigEndian.Uint16(ends[i*2:]))
				start := rune(binary.BigEndian.Uint16(starts[i*2:]))
				if c < start || c > end {
					continue
				}
				delta, offset := binary.BigEndian.Uint16(deltas[i*2:]), binary.BigEndian.Uint16(offsets[i*2:])
				if offset == 0 {
					return int(uint16(c) + delta)
				}
				at := i*2 + int(offset) + int(c-start)*2
				if at+2 > len(offsets) {
					return 0
				}
				glyph := binary.BigEndian.Uint16(offsets[at:])
				if glyph == 0 {
					return 0
				}
				return int(glyph + delta)
			}
			return 0
		}, nil
	}
	return nil, fmt.Errorf("no Unicode cmap subtable of format 4 or 12")
}
